#!/usr/bin/env bash
# barycenter — 전체 검증. 지금 어디까지 확인됐는지 한 번에 본다.
#
#   ./scripts/verify.sh              전부
#   ./scripts/verify.sh --quick      도커가 필요 없는 것만 (단위 + 타입)
#   ./scripts/verify.sh --group e2e  조각 하나만 (CI 가 병렬로 돌리는 단위)
#   ./scripts/verify.sh --list-groups  조각 이름 목록
#   ./scripts/verify.sh --verbose    통과한 단위의 출력도 전부 낸다
#   ./scripts/verify.sh --no-live    자식의 진행 줄을 안 흘려보낸다 (표만)
#
# 도커가 필요한 묶음(골든·엔진·스파이크)은 도커가 없으면 **건너뛰지 않고 실패**한다.
# 조용히 건너뛰면 통과 신호를 위조하게 된다. 굳이 빼려면 --quick 을 명시한다.
#
# **조각의 정의도 여기 있다.** 이 스크립트는 873초를 직렬로 돌았고, 단위 열여덟이
# 서로를 안 기다리는데도 그랬다. 나누면 임계 경로가 가장 긴 단위 하나로 줄어든다.
# 그 목록을 CI 에 적으면 로컬과 갈라지고, 갈라지면 어느 쪽이 계약인지 아무도 모른다 —
# 이 저장소가 문서와 코드에서 이미 겪은 병이다. 그래서 CI 는 `--list-groups` 로
# **이름만** 받아 매트릭스를 만들고, 무엇이 어느 조각인지는 아래 `group` 이 정한다.

set -uo pipefail
cd "$(dirname "${BASH_SOURCE[0]}")/.."

# **게이트가 자기 흔들림을 센다** (검수 W4-9). 근거는 그 파일 머리말에 있다.
# shellcheck source=lib/flake.sh
. scripts/lib/flake.sh
# 진행 표시. **판정을 나르는 코드라** 별도 파일이고, 아래 게이트가 그것을 잰다.
# shellcheck source=lib/live.sh
. scripts/lib/live.sh
FLAKES=0

# 조각. 순서는 CI 매트릭스에 그대로 나가므로 **긴 것을 앞에** 둔다 —
# 러너가 순서대로 집으면 가장 늦게 끝날 것이 가장 먼저 시작한다.
# ⚠️ `GROUPS` 라는 이름은 쓸 수 없다 — bash 내장 배열(현재 사용자의 그룹 ID)이라
#    대입이 먹지 않고 GID 목록이 튀어나온다. 실제로 한 번 그렇게 나왔다.
VERIFY_GROUPS=(e2e engine render spikes unit)
# 이 중 도커가 필요한 것들. `unit` 만 도커 없이 돈다.
VERIFY_DOCKER_GROUPS=(e2e engine render spikes)

QUICK=0
GROUP=""
VERBOSE=0
while [ $# -gt 0 ]; do
  case "$1" in
    --quick)       QUICK=1 ;;
    --verbose|-v)  VERBOSE=1 ;;
    --no-live)     BARY_VERIFY_LIVE=0 ;;
    --group)       shift; GROUP="${1:-}" ;;
    --group=*)     GROUP="${1#--group=}" ;;
    --list-groups) printf '%s\n' "${VERIFY_GROUPS[@]}"; exit 0 ;;
    *) echo "알 수 없는 인자: $1" >&2; exit 2 ;;
  esac
  shift
done

if [ -n "$GROUP" ]; then
  case " ${VERIFY_GROUPS[*]} " in
    *" $GROUP "*) ;;
    *) echo "알 수 없는 조각: $GROUP (있는 것: ${VERIFY_GROUPS[*]})" >&2; exit 2 ;;
  esac
fi

# 지금 어느 조각을 적고 있는가. `run` 이 이걸 보고 자기가 돌 차례인지 판단한다.
CURRENT_GROUP=""
RAN=0

group() {
  local g="$1"
  # 오타로 조각을 새로 만들지 못하게 한다. 없는 이름으로 묶으면 그 단위는 어느
  # 매트릭스 칸에서도 안 돌면서 **아무도 그 사실을 모른다** — 나누기의 대표적 사고다.
  case " ${VERIFY_GROUPS[*]} " in
    *" $g "*) ;;
    *) echo "  FAIL  알 수 없는 조각: $g" >&2; exit 2 ;;
  esac
  CURRENT_GROUP="$g"
}

# 지금 고른 조각이 도커를 필요로 하는가.
needs_docker() {
  [ $QUICK -eq 1 ] && return 1
  [ -z "$GROUP" ] && return 0
  case " ${VERIFY_DOCKER_GROUPS[*]} " in *" $GROUP "*) return 0 ;; *) return 1 ;; esac
}

RESULTS=()
FAILED=0
STARTED=$(date +%s)

# **도는 중이라는 것을 말한다.**
#
# 원래 이 스크립트는 끝날 때까지 한 글자도 내지 않았다. 자식의 출력을 삼켜서 표
# 하나로 보여 주는 것이 값이지만, e2e·스파이크는 하나가 십 분을 넘긴다 — 그 동안
# 화면은 **멎은 것과 구분되지 않는다**. CI 에서는 더 나빴다: 60분 타임아웃에 걸려도
# 로그는 어느 스위트에서 멎었는지 말하지 않았다.
#
# 출력을 흘려 보내는 것으로 고치지 않는다. 그러면 표가 없어진다. 대신 세 가지를 낸다:
#   (1) 무엇을 지금 시작했는지        — 시작 줄
#   (2) 아직 살아 있다는 신호         — 심장박동
#   (3) 끝나는 즉시 판정과 걸린 시간  — 마지막에 몰아 찍지 않는다
#
# 터미널이면 점을 한 줄에 이어 찍고 판정으로 그 줄을 덮는다. 파이프·CI 로그면
# 되감기가 없으므로 줄을 새로 낸다 — 타임스탬프가 붙는 쪽이라 그편이 낫다.
TTY=0; [ -t 1 ] && TTY=1
if [ $TTY -eq 1 ]; then BEAT=${BARY_VERIFY_HEARTBEAT:-15}
else                    BEAT=${BARY_VERIFY_HEARTBEAT:-60}
fi

# **자식이 무엇을 하고 있는지 흘려보낸다** (`--no-live` 로 끈다).
#
# 심장박동은 *"아직 살아 있다"* 만 말한다. 그런데 e2e 가 십 분을 도는 동안 알고 싶은
# 것은 그것이 아니라 **지금 무엇을 하고 있고 어디까지 됐는가** 다 — 패키지 매니저가
# 무엇을 받고 무엇을 푸는지 한 줄씩 내는 것과 같은 이유다. 멎은 것과 오래 걸리는 것을
# 가르는 데는 "60초째" 보다 "지금 이 파일을 돌고 있다" 가 낫다.
#
# ⚠️ **fd 3 이 필요하다.** `bary_run_twice` 는 진단을 위해 자식의 출력을 `$(...)` 로
# 통째로 붙잡는다(그 값은 그대로 둔다 — 실패했을 때 원문이 없으면 아무것도 못 한다).
# 그 안에서 그냥 찍으면 캡처로 들어가 화면에는 안 나온다. 그래서 캡처 **밖**으로 나가는
# 통로를 하나 연다.
exec 3>&1
BARY_LIVE=${BARY_VERIFY_LIVE:-1}
export BARY_LIVE

heartbeat() {                # heartbeat <label>
  local label="$1" t=0
  while true; do
    # **`sleep` 의 출력을 끊어 둔다.** 심장박동을 kill 해도 그 순간 돌던 `sleep` 은
    # 고아로 남아 최대 $BEAT 초를 더 산다. 그게 스크립트의 stdout(=CI 스텝의 파이프)을
    # 물고 있으면 **스텝이 그만큼 안 끝난다** — 배경 프로세스가 파이프를 잡고 있는
    # 그 함정이다. 시간만 재는 프로세스에 출력은 필요 없다.
    sleep "$BEAT" >/dev/null 2>&1
    t=$(( t + BEAT ))
    # 진행을 흘리는 중이면 같은 모양으로 낸다 — 점만 찍으면 진행 줄 사이에서 뜬다.
    if [ "$BARY_LIVE" -eq 1 ]; then
      printf '     │  … %s초째 도는 중\n' "$t"
    elif [ $TTY -eq 1 ]; then
      printf '.'
    else
      printf '  ..    %s  —  %s초째 도는 중\n' "$label" "$t"
    fi
  done
}

run() {                      # run <label> [--what <설명>] <command...>
  local label="$1"; shift
  local out rc hb start elapsed line what=""
  # **그 단계가 무엇을 하는지 적는다.** 라벨은 이름일 뿐이라 `typecheck` 가 무엇을
  # 검사하고 무엇을 안 내는지 말하지 않는다. 설명은 시작 줄에 붙는다.
  if [ "${1:-}" = --what ]; then shift; what="$1"; shift; fi

  # **조각에 배정되지 않은 단위는 없다.** 나누면서 조용히 빠뜨리는 것이 이 구조에서
  # 가장 비싼 사고다 — 검사가 사라진 것이 초록으로 보이기 때문이다. 스파이크를 하나
  # 더 넣고 `group` 뒤에 두는 것을 잊으면 여기서 즉시 빨개진다.
  if [ -z "$CURRENT_GROUP" ]; then
    printf '  FAIL  %s — 어느 조각에도 없다 (`group <이름>` 뒤에 두어라)\n' "$label" >&2
    FAILED=1
    return
  fi
  # 조각 하나만 도는 중이면 남의 것은 건너뛴다.
  if [ -n "$GROUP" ] && [ "$CURRENT_GROUP" != "$GROUP" ]; then
    return 0
  fi
  RAN=$(( RAN + 1 ))
  # **진행을 흘릴 때는 줄을 닫는다.** 안 닫으면 아래 진행 줄이 이 줄 뒤에 붙고,
  # 끝에서 `\r` 로 덮으면 진행 줄까지 함께 지워진다.
  if [ "$BARY_LIVE" -eq 1 ]; then
    printf '  ..    %s  —  %s\n' "$label" "${what:-시작}"
  elif [ $TTY -eq 1 ]; then
    printf '  ..    %s  —  %s' "$label" "${what:-}"
  else
    printf '  ..    %s  —  %s\n' "$label" "${what:-시작}"
  fi

  start=$(date +%s)
  heartbeat "$label" &
  hb=$!
  # **실패하면 한 번 더 돈다** (검수 W4-9). ⚠️ 재실행이 **판정을 안 바꾼다** —
  # 두 번째가 초록이어도 이 스위트는 실패로 세고 게이트는 빨갛다. 재실행이 사는 이유는
  # 「흔들렸다」를 「깨졌다」와 구분해 **적기** 위해서이지 통과시키기 위해서가 아니다.
  bary_run_twice bary_live "$@"
  out=$BARY_RUN_OUT; rc=$BARY_RUN_RC
  { kill "$hb"; wait "$hb"; } 2>/dev/null
  elapsed=$(( $(date +%s) - start ))

  if [ $rc -eq 0 ]; then
    line="  ok    $label  —  $(summarize "$out")  (${elapsed}초)"
  elif [ "$BARY_RUN_FLAKE" -eq 1 ]; then
    # **흔들림도 빨강이다.** 다만 표에서 구분해 보이고 장부에 남는다.
    line="  FLAKE $label  —  $(summarize "$out")  (${elapsed}초) ← 재실행은 초록"
    FAILED=1
    FLAKES=$(( FLAKES + 1 ))
    bary_record_flake "$label" "$elapsed"
  else
    line="  FAIL  $label  —  $(summarize "$out")  (${elapsed}초)"
    FAILED=1
  fi
  RESULTS+=("$line")

  # 터미널이면 진행 줄을 지우고 그 자리에 판정을 덮는다.
  # 진행을 흘리는 중이면 덮을 것이 없다 — 이미 줄을 닫았다.
  [ $TTY -eq 1 ] && [ "$BARY_LIVE" -eq 0 ] && printf '\r\033[K'
  printf '%s\n' "$line"

  # **통과한 단위의 출력도 볼 수 있어야 한다.**
  #
  # 이 스크립트는 자식의 출력을 삼켜 표 하나로 보여 준다(머리말 참조). 그 값은
  # 그대로지만, 실패했을 때만 원문이 나오면 **"왜 통과했는지" 를 되짚을 수 없다** —
  # 스위트가 0 건을 돌고 초록인 경우가 표에서는 통과와 똑같이 보인다.
  #
  # CI 에서는 접힌 그룹으로 낸다. 표는 그대로 읽히고, 궁금한 줄만 펼치면 원문이 있다.
  # 로컬에서는 `--verbose` 로 같은 것을 낸다.
  if [ -n "${GITHUB_ACTIONS:-}" ]; then
    # ⚠️ 자식의 출력에 `::error::` 같은 줄이 섞이면 GitHub 이 그걸 **명령으로 실행**해
    #    가짜 주석이 달린다. 원문을 내는 동안 명령 해석을 끈다. 토큰은 매번 달라야
    #    출력이 그것을 흉내 내 다시 켜는 것을 막는다.
    local tok="verify-$$-${RANDOM}${RANDOM}"
    printf '::group::%s  (%s초)\n' "$label" "$elapsed"
    printf '::stop-commands::%s\n' "$tok"
    printf '%s\n' "$out"
    printf '::%s::\n' "$tok"
    printf '::endgroup::\n'
  elif [ $VERBOSE -eq 1 ]; then
    printf '\n----- %s (전문) -----\n%s\n' "$label" "$out"
  fi

  if [ $rc -ne 0 ]; then
    # **꼬리 25 줄로는 모자란다.** 스파이크는 실패한 회차의 진단을 **인라인**으로 찍고
    # 요약을 맨 뒤에 찍는다 — 꼬리만 보면 요약만 남고 원인은 잘린다. S12 가 게이트
    # 안에서만 떨어질 때 정확히 그래서 "왜" 를 못 봤다.
    #
    # 실패 표식(`FAIL `·`bad `·`Error`·`error.log`)이 있는 줄과 그 뒤 몇 줄을 함께 낸다.
    # 아무것도 안 걸리면 예전처럼 꼬리를 낸다 — 못 찾는 것보다 낫다.
    local marked
    marked=$(echo "$out" | grep -nE '^\s*(FAIL|bad|✗)|Error|error\.log|복구 로그|후속 로그' | head -20)
    if [ -n "$marked" ]; then
      printf '\n----- %s (표식 줄) -----\n%s\n' "$label" "$(echo "$out" \
        | grep -E -A 6 '^\s*(FAIL|bad|✗)|Error|error\.log|복구 로그|후속 로그' | head -80)"
    fi
    printf '\n----- %s (꼬리) -----\n%s\n' "$label" "$(echo "$out" | tail -25)"
  fi
}

summarize() {
  # `||` 를 파이프라인에 걸면 안 잡힌다 — 마지막 `tr` 이 0 으로 끝나므로 grep 이
  # 아무것도 못 찾아도 "완료" 가 안 나오고 **빈 칸**이 남았다. 값을 받아서 본다.
  local s
  # **실패 모양도 잡는다.** 성공 모양만 알면 빨간 단계의 요약이 마지막 줄로 떨어지고,
  # vitest 의 마지막 줄은 `Duration …` 이라 **무엇이 몇 개 깨졌는지가 안 보인다.**
  # 정작 알고 싶을 때 못 알려 주는 셈이라 그 자리가 제일 아쉽다.
  s=$(echo "$1" | grep -oE 'Tests +[0-9]+ (failed|passed)[^(]*\([0-9]+\)|PASS=[0-9]+ +FAIL=[0-9]+( +SKIP=[0-9]+)?' \
      | tail -1 | tr -s ' ')
  if [ -n "$s" ]; then echo "$s"; return; fi

  # **도구가 낸 마지막 줄을 그대로 쓴다.**
  #
  # 전에는 위 두 모양(vitest · 스파이크)만 알고 나머지를 전부 `완료` 로 접었다. 그런데
  # 그 도구들은 이미 쓸 만한 한 줄을 내고 있었고 그것이 버려지고 있었다:
  #
  #   node-pin    node 24 — .nvmrc · deploy/Dockerfile(24, 24) · engines ">=22"
  #   reachable   도달성 ok — 92 파일, 예외 20 건
  #   surface     표면 그대로 — 117 심볼 · sha256:… · 동결 카운터 3 회차 · A 미선언
  #
  # 도구마다 정규식을 새로 짜는 대신 마지막 의미 있는 줄을 쓴다 — 새 단계를 넣을 때
  # 여기를 안 고쳐도 되고, 도구가 자기 출력을 좋게 만들면 표도 저절로 좋아진다.
  #
  # 배너로 끝나는 도구가 있으면 그 배너가 요약이 된다. 그때 고칠 곳은 **도구의 마지막
  # 줄**이지 여기가 아니다 — 표가 도구의 출력을 해석하기 시작하면 자리가 둘이 된다.
  local esc; esc=$(printf '\033')
  s=$(printf '%s' "$1" \
      | sed "s/${esc}\[[0-9;]*[A-Za-z]//g" \
      | grep -vE '^[[:space:]]*$' \
      | tail -1 \
      | sed 's/^[[:space:]]*//; s/[[:space:]]*$//')

  # **출력이 없는 것도 결과다.** `tsc` 는 통과하면 한 글자도 안 낸다 — 그걸 `완료` 라고
  # 적으면 무엇을 보고 통과라 했는지가 사라진다.
  if [ -z "$s" ]; then echo "출력 없음 (조용히 통과)"; return; fi
  printf '%s\n' "$s" | sed 's/\(.\{56\}\).*/\1…/'
}

