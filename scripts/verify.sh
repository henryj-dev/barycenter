run() {                      # run <label> <command...>
  local label="$1"; shift
  local out rc
  out=$("$@" 2>&1); rc=$?
  if [ $rc -eq 0 ]; then
    RESULTS+=("  ok    $label  —  $(summarize "$out")")
  else
    RESULTS+=("  FAIL  $label  —  $(summarize "$out")")
    FAILED=1
    printf '\n----- %s -----\n%s\n' "$label" "$(echo "$out" | tail -25)"
  fi
}

summarize() {
  echo "$1" | grep -oE 'Tests +[0-9]+ passed \([0-9]+\)|PASS=[0-9]+ +FAIL=[0-9]+( +SKIP=[0-9]+)?' \
    | tail -1 | tr -s ' ' || echo "완료"
}

