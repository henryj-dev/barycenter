# 진행 표시 — 자식이 지금 무엇을 하고 있는지 흘려보낸다.
#
# **왜 있나.** 심장박동은 *"아직 살아 있다"* 만 말한다. 그런데 e2e 가 십 분을 도는 동안
# 알고 싶은 것은 그것이 아니라 **지금 무엇을 하고 있고 어디까지 됐는가** 다 — 패키지
# 매니저가 무엇을 받고 무엇을 푸는지 한 줄씩 내는 것과 같은 이유다. 멎은 것과 오래
# 걸리는 것을 가르는 데는 "60초째" 보다 "지금 이 파일을 돌고 있다" 가 낫다.
#
# ⚠️ **fd 3 으로 낸다.** `bary_run_twice` 는 진단을 위해 자식의 출력을 `$(...)` 로 통째로
# 붙잡는다(그 값은 그대로 둔다 — 실패했을 때 원문이 없으면 아무것도 못 한다). 그 안에서
# 그냥 찍으면 캡처로 들어가 화면에는 안 나온다. 그래서 캡처 **밖**으로 나가는 통로를
# 쓴다. 여는 것은 부르는 쪽의 몫이다 (`exec 3>&1`).
#
# ⚠️ **이 파일이 판정을 나른다.** `bary_live` 는 자식을 파이프라인으로 감싸므로, 종료코드
# 전달이 여기서 틀리면 **게이트가 영원히 초록이 된다.** 그래서 `flake.sh` 와 같은 대접을
# 한다 — 별도 파일로 두고 `test-live.py` 가 실물 셸에서 잰다.

# 낼 만한 줄인가. **모르는 모양은 안 낸다** — 넓게 잡으면 소음이 들어오고, 그러면 사람이
# 이 줄들을 안 읽게 된다. 안 읽히는 진행 표시는 없는 것과 같다.
bary_live_pick() {           # bary_live_pick <다듬은 줄>  → 낼 것이면 0
  case "$1" in
    # vitest 의 파일·항목 판정 (`✓ tests/x.test.ts (12 tests) 340ms`)
    *"✓ "*.test.ts*|*"×"*.test.ts*|*"❯ "*.test.ts*) return 0 ;;
    # 항목 단위 판정 — 스파이크·훅·설치 하네스가 같은 모양을 쓴다
    "PASS"*|"FAIL"*|"NO "*|"✓ "*|"✗ "*|"× "*) return 0 ;;
    # 무대 준비. 오래 걸리는 자리라 이것이 보이는 것이 값이다
    *"docker pull"*|*"컨테이너 기동"*|*"판 이미지 빌드"*|*"이미지 준비"*) return 0 ;;
  esac
  # **도구의 결론 줄은 안 낸다.** 그건 표의 요약이 싣는다 — 여기서도 내면 한 단계가 같은
  # 말을 두 번 하고, 그러면 진행 줄이 무엇을 위한 것인지 흐려진다.
  return 1
}

# 한 줄을 화면 모양으로 다듬는다. ANSI 를 벗기고 앞뒤 공백을 털고 길면 자른다 —
# `.` 는 UTF-8 로케일에서 글자 하나라 한글이 안 쪼개진다.
bary_live_render() {         # bary_live_render <줄>
  local esc; esc=$(printf '\033')
  printf '%s' "$1" \
    | sed "s/${esc}\[[0-9;]*[A-Za-z]//g; s/^[[:space:]]*//; s/[[:space:]]*$//" \
    | sed 's/\(.\{88\}\).*/\1…/'
}

# 자식을 돌리면서 진행을 흘린다.
#
# 표준출력은 그대로 캡처로 가고(진단이 그것을 쓴다), 고른 줄만 fd 3 으로 화면에 간다.
# `bary_run_twice` 가 이 함수를 두 번 부를 수 있다 — 재실행이면 그것도 그대로 보인다.
#
# `BARY_LIVE_MAX` 를 넘으면 멈추되 **그 사실을 말한다.** 조용히 자르면 표시가 거짓이 된다.
bary_live() {                # bary_live <cmd...>
  local line rc n=0 max=${BARY_LIVE_MAX:-400}
  "$@" 2>&1 | while IFS= read -r line; do
    printf '%s\n' "$line"
    [ "${BARY_LIVE:-1}" -eq 1 ] || continue
    [ "$n" -ge "$max" ] && continue
    # **다듬어서 판정한다.** 도구마다 들여쓰기가 달라, 안 다듬으면 같은 모양인데
    # 어떤 것은 걸리고 어떤 것은 안 걸린다.
    if bary_live_pick "$(bary_live_render "$line")"; then
      n=$(( n + 1 ))
      if [ "$n" -eq "$max" ]; then
        printf '     │  … 진행 줄 %s 개를 넘었다. 나머지는 --verbose 로 본다\n' "$max" >&3
      else
        printf '     │  %s\n' "$(bary_live_render "$line")" >&3
      fi
    fi
  done
  # **`$?` 를 쓰면 안 된다** (검수 2026-08-29(4) · `test-live.py` 가 잡았다).
  #
  # 파이프라인의 `$?` 는 **마지막 명령**의 것이고 여기서 마지막은 `while` 이다 — 언제나
  # 0 이다. `set -o pipefail` 이 켜져 있으면 우연히 맞지만, 그러면 이 함수의 옳음이
  # **부르는 쪽의 셸 옵션**에 매달린다. 게이트의 판정을 나르는 코드가 남의 설정에 기대면
  # 그 설정이 바뀌는 날 **모든 실패가 조용히 초록이 된다.**
  #
  # `PIPESTATUS[0]` 은 옵션과 무관하게 자식의 것이다. 파이프라인 직후에 읽어야 한다.
  rc=${PIPESTATUS[0]}
  return "$rc"
}
