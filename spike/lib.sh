# shellcheck shell=bash
#
# **스파이크 공용 — 컨테이너에 넘길 작업 디렉토리** (검수 2026-08-24 CI-1)
#
# ── 왜 있는가
#
# S15 가 CI 에서 빨갰다. 로컬(macOS)에서는 초록이었다:
#
#   [error] failed to load external Lua file "/w/probe.lua": Permission denied
#
# `mktemp -d` 는 **0700** 을 만든다. 스파이크는 그 디렉토리를 엔진 컨테이너에
# bind-mount 하는데, 컨테이너 안의 nginx 워커는 `nobody` 이고 배포 이미지의 데몬은
# `bary`(10001) 다. 둘 다 호스트 사용자가 아니므로 **디렉토리를 통과하지 못한다.**
#
# ── 왜 로컬에서는 안 잡혔나
#
# macOS 의 Docker Desktop 은 bind-mount 를 VM 을 거쳐 넘기면서 소유권·모드를 컨테이너
# 사용자 쪽으로 바꿔 준다. 그래서 **같은 스크립트가 같은 이미지로 macOS 에서는 초록,
# 리눅스에서는 빨갛다.** 이 저장소가 이미 적어 둔 자리다 — *"흉내로 재면 흉내를 재게
# 된다"*: 여기서 흉내를 낸 것은 우리가 아니라 개발 기계의 파일시스템이었다.
#
# ── 왜 함수로 빼는가
#
# 같은 패턴이 S10·S15·S20 셋에 있었다. 하나만 고치면 나머지 둘은 **다음 사람이 리눅스에서
# 처음 돌릴 때** 같은 자리에 다시 물린다. 이 저장소가 적어 둔 대로 *"목록으로 관리하다
# 물린 자리가 이미 여럿"* 이라, 목록 대신 한 자리로 만든다.

# `bary_spike_workdir` — 컨테이너가 읽을 수 있는 임시 디렉토리를 만들어 stdout 으로 낸다.
#
# 0755 다. 여기 들어가는 것은 스파이크가 방금 만든 설정·프로브뿐이고 비밀은 없다.
bary_spike_workdir() {
  _w="$(mktemp -d)" || return 1
  chmod 0755 "$_w" || return 1
  printf '%s' "$_w"
}

# `bary_spike_readable <path...>` — 컨테이너 안에서 읽을 파일의 모드를 맞춘다.
#
# `cat > file` 로 만든 파일은 호스트 umask 를 탄다. 개발 기계가 `umask 077` 이면
# 0600 이 되어 디렉토리를 열어 둬도 파일에서 다시 막힌다.
bary_spike_readable() {
  chmod 0644 "$@"
}
