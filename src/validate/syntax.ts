/**
 * 경로 조각이 되는 이름의 문법 — **규칙마다 한 벌만 둔다**
 *
 * ── 왜 파일 하나에 모으는가
 *
 * 사용자가 정한 문자열이 파일시스템 경로 조각이 되는 자리가 셋이다:
 *
 *   `src/store/config-store.ts`  리소스 key. `certs/<key>/<version>/privkey.pem`
 *                                으로 세대에 들어가고 ACME 가 `acme-<key>` 로 쓴다
 *   `src/dp/secrets*.ts`         시크릿 이름. 위의 `acme-<key>` 와 인증서 key 가 여기로 온다
 *   `src/dp/wire.ts`             원격 창구의 `targetGeneration`. `generations/<이름>`
 *                                이 되고 `BARY_CONFIGTEST_CMD` 의 `{generation}` 자리로
 *                                간다 — 그 문자열은 `/bin/sh -c` 에 들어간다
 *
 * **세 규칙은 서로 맞물려야 한다.** 리소스 key 로 받은 것을 시크릿 이름이 거절하면 "모델에는
 * 저장되는데 ACME 가 그 인증서만 발급 못 하는" 조합이 생긴다. 그래서 시크릿 이름은 리소스
 * key 가 쓰는 글자를 **모두** 받는다.
 *
 * 그러면 왜 `validate/strings.ts` 에 안 두는가. 그 파일은 `./ip.js` 와
 * `../model/provisional.js` 를 끌어온다. **`src/dp/` 는 모델 층을 안 본다** — DP
 * 에이전트는 nginx 옆에서 도는 별도 배포이고, 그 경계를 지키는 것이 §3.1 이다. 규칙
 * 하나를 나눠 쓰려고 그 경계를 무르는 것은 값이 안 맞는다. 그래서 **아무것도 import
 * 하지 않는 잎**으로 둔다.
 *
 * 사본을 여러 벌로 두는 선택지도 있었다. 이 저장소가 그걸로 이미 여러 번 물렸다 —
 * `build.sh` 의 진입점 목록(N1), `assertDirectiveStrings` 의 필드 목록(N3). 자리가
 * 둘이면 언젠가 갈리고, 갈린 뒤에는 어느 쪽이 정본인지 아무도 모른다.
 */

/**
 * **세대 이름** — 영숫자로 시작하고, 영숫자·점·밑줄·하이픈만, 63 자까지.
 *
 * 선두를 영숫자로 제한하는 것은 `.`·`..`·`-flag` 를 **한 번에** 막기 위해서다.
 *
 * ⚠️ **`/` 도 `..` 도 못 들어간다는 것이 이 정규식의 일이다.** 셸 메타문자(`;`·`$`·
 * 백틱·공백)가 막히는 것은 그 덤이지 목적이 아니다 — 목적이 셸 안전이었다면 인용을
 * 했을 것이고, 인용은 이 값이 가는 **모든** 자리를 우리가 안다고 가정한다.
 *
 * 리소스 key 가 `:` 와 127 자를 받게 된 뒤에도(2026-11-20) **이것은 넓히지 않았다** —
 * 세대 이름은 사용자가 아니라 barycenter 가 짓고(`r<리비전>-e<epoch>`), 셸 인자 자리로 간다.
 * 넓혀서 얻는 것이 없다.
 */
export const PATH_SEGMENT_SYNTAX = /^[A-Za-z0-9][A-Za-z0-9._-]{0,62}$/;

/** 사람이 읽는 규칙 설명. 거절 메시지가 규칙을 스스로 말하게 한다. */
export const PATH_SEGMENT_RULE =
  '영숫자로 시작하고 영숫자·점·밑줄·하이픈만, 63 자까지다';

/**
 * **리소스 key** — 구간을 `:` 로 잇는다. 127 자까지 (2026-11-20).
 *
 * 각 구간은 세대 이름과 같은 규칙이다: 영숫자로 시작하고 영숫자·점·밑줄·하이픈만.
 * 빈 구간(`::`, 맨 앞·맨 뒤 `:`)은 없다.
 *
 * 왜 `:` 인가. 운영자가 `{호스트}:{서비스}[:{세부}][:{분산 구분}]` 으로 이름을 짓는다 —
 * 예: `web-01.dc1:shop:api:01`. `.` 는 호스트 이름 안에서 이미 쓰이므로
 * 구분자가 못 된다. `:` 는 리눅스 경로 조각에서 특별한 뜻이 없고, nginx 에서는 key 가
 * 식별자로 갈 때 `ident()` 가 바꾼다.
 *
 * 왜 127 자인가. 호스트 FQDN 하나가 이미 수십 자다. nginx 변수 이름의 상한(46 자)은
 * `nginxVar` 가 잘라서 지킨다 — key 길이와 따로 논다.
 *
 * ⚠️ 전에는 `:` 가 시스템이 짓는 이름의 구분자였다(HTTPS 리스너의 평문 리다이렉트 소켓
 * `<리스너>:http`). 그 자리는 이제 `~` 다(`model/redirect.ts`) — `~` 는 여전히 key 에 못 쓴다.
 */
export const RESOURCE_KEY_SYNTAX = /^(?=.{1,127}$)[A-Za-z0-9][A-Za-z0-9._-]*(?::[A-Za-z0-9][A-Za-z0-9._-]*)*$/;

/** 사람이 읽는 리소스 key 규칙. 서버 거절 메시지가 쓴다. */
export const RESOURCE_KEY_RULE =
  '구간을 콜론(:)으로 잇고, 각 구간은 영숫자로 시작해 영숫자·점·밑줄·하이픈만 쓴다. 127 자까지다';

/**
 * **시크릿 이름** — 리소스 key 가 쓰는 글자를 모두 받는다(위 머리말).
 *
 * `acme-<key>` 처럼 key 에 앞말을 붙인 것이 오므로 리소스 key 규칙을 그대로 쓰지 않는다.
 * 길이 상한도 안 둔다 — 파일 이름 상한(255)은 key 상한(127)에 앞말을 붙여도 멀다.
 * `/` 와 `..` 은 여전히 못 들어간다(`.` 만으로 된 이름은 아래에서 따로 막는다).
 */
export const SECRET_NAME_SYNTAX = /^[A-Za-z0-9._:-]+$/;

/** 시크릿 이름으로 쓸 수 있는가. `.`·`..` 은 경로를 바꾸므로 글자가 맞아도 거절한다. */
export const isSecretName = (name: string): boolean =>
  SECRET_NAME_SYNTAX.test(name) && name !== '.' && name !== '..';
